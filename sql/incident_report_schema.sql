CREATE TABLE IF NOT EXISTS incident_report_ocr (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  report_no VARCHAR(40) NOT NULL,
  incident_id INT NULL,
  incident_date DATE NULL,
  machine_id VARCHAR(64) NULL,
  location_raw TEXT NULL,
  emp_code VARCHAR(32) NULL,
  description TEXT NULL,
  severity_raw INT NULL,
  severity_scale VARCHAR(32) NOT NULL,
  scale_source VARCHAR(32) NOT NULL,
  severity_5_worst INT NULL,
  lost_days INT NULL,
  reporting TEXT NULL,
  immediate_action TEXT NULL,
  root_cause_reference TEXT NULL,
  image_path TEXT NOT NULL,
  image_sha256 CHAR(64) NOT NULL,
  ocr_confidence DECIMAL(5,2) NULL,
  extraction_flags JSON NOT NULL,
  ocr_raw_json JSON NOT NULL,
  review_status VARCHAR(32) NOT NULL DEFAULT 'PENDING_REVIEW',
  imported_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY uq_incident_report_no (report_no),
  KEY idx_incident_report_machine (machine_id),
  KEY idx_incident_report_date (incident_date),
  KEY idx_incident_report_review (review_status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;